import 'dart:io';

import 'package:archive/archive_io.dart';
import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';

import '../models/task.dart';
import '../services/task_service.dart';

/// Простой BuilderAgent — создаёт минимальный Flutter-проект и упаковывает в ZIP.
/// На MVP работает без реального LLM (жёсткая логика). Позже можно обернуть в tool-calling.
class BuilderAgent {
  final TaskService taskService;
  final String agentId;

  BuilderAgent({
    required this.taskService,
    required this.agentId,
  });

  Future<void> execute(Task task) async {
    try {
      await taskService.startTask(task.id);
      await taskService.addLog(task.id, 'BuilderAgent начал работу');

      // 1. Создаём временную директорию проекта
      final tempDir = await getTemporaryDirectory();
      final projectName = task.metadata['projectName'] as String? ?? 'hello_agent';
      final projectDir = Directory(p.join(tempDir.path, 'agent_builds', projectName));

      if (await projectDir.exists()) {
        await projectDir.delete(recursive: true);
      }
      await projectDir.create(recursive: true);

      await taskService.updateProgress(task.id, 0.15);
      await taskService.addLog(task.id, 'Создаю структуру Flutter-проекта...');

      // 2. Генерируем минимальные файлы
      await _writeFile(
        p.join(projectDir.path, 'pubspec.yaml'),
        _pubspecContent(projectName),
      );
      await _writeFile(
        p.join(projectDir.path, 'lib', 'main.dart'),
        _mainDartContent(projectName),
      );
      await _writeFile(
        p.join(projectDir.path, 'README.md'),
        '# $projectName\n\nСгенерировано Agent City BuilderAgent\n',
      );
      await _writeFile(
        p.join(projectDir.path, 'analysis_options.yaml'),
        'include: package:flutter_lints/flutter.yaml\n',
      );

      await taskService.updateProgress(task.id, 0.45);
      await taskService.addLog(task.id, 'Файлы проекта созданы');

      // 3. Упаковываем в ZIP
      await taskService.addLog(task.id, 'Создаю ZIP-архив...');
      final docsDir = await getApplicationDocumentsDirectory();
      final zipPath = p.join(docsDir.path, 'agent_city', '$projectName.zip');
      await Directory(p.dirname(zipPath)).create(recursive: true);

      final encoder = ZipFileEncoder();
      encoder.create(zipPath);
      encoder.addDirectory(projectDir, includeDirName: true);
      encoder.close();

      await taskService.updateProgress(task.id, 0.85);
      await taskService.addLog(task.id, 'ZIP создан: $zipPath');

      // 4. Готово
      final result = {
        'zipPath': zipPath,
        'projectName': projectName,
        'sizeBytes': await File(zipPath).length(),
      };

      await taskService.completeTask(
        task.id,
        result: 'ZIP готов: $zipPath (${result['sizeBytes']} bytes)',
      );

      // Можно сразу поставить задачу на деплой
      // (в реальной системе это делает оркестратор)
    } catch (e, st) {
      await taskService.failTask(task.id, e.toString());
      await taskService.addLog(task.id, 'Stack: $st');
    }
  }

  Future<void> _writeFile(String path, String content) async {
    final file = File(path);
    await file.parent.create(recursive: true);
    await file.writeAsString(content);
  }

  String _pubspecContent(String name) => '''
name: $name
description: Generated by Agent City
publish_to: 'none'
version: 0.1.0+1

environment:
  sdk: '>=3.5.0 <4.0.0'

dependencies:
  flutter:
    sdk: flutter
  cupertino_icons: ^1.0.8

dev_dependencies:
  flutter_test:
    sdk: flutter
  flutter_lints: ^5.0.0

flutter:
  uses-material-design: true
''';

  String _mainDartContent(String name) => '''
import 'package:flutter/material.dart';

void main() {
  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: '$name',
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: Colors.deepPurple),
        useMaterial3: true,
      ),
      home: const MyHomePage(title: '$name'),
    );
  }
}

class MyHomePage extends StatefulWidget {
  const MyHomePage({super.key, required this.title});
  final String title;

  @override
  State<MyHomePage> createState() => _MyHomePageState();
}

class _MyHomePageState extends State<MyHomePage> {
  int _counter = 0;

  void _incrementCounter() {
    setState(() {
      _counter++;
    });
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        backgroundColor: Theme.of(context).colorScheme.inversePrimary,
        title: Text(widget.title),
      ),
      body: Center(
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            const Text('You have pushed the button this many times:'),
            Text(
              '\$_counter',
              style: Theme.of(context).textTheme.headlineMedium,
            ),
          ],
        ),
      ),
      floatingActionButton: FloatingActionButton(
        onPressed: _incrementCounter,
        tooltip: 'Increment',
        child: const Icon(Icons.add),
      ),
    );
  }
}
''';
}