import 'dart:async';

import '../connectors/connectors.dart';
import '../models/task.dart';
import '../services/notification_service.dart';
import '../services/task_service.dart';

/// DeployerAgent — использует GitHubConnector.
/// Умеет: создать репо → залить ZIP → запустить Actions → ждать APK → уведомить.
class DeployerAgent {
  final TaskService taskService;
  final String agentId;

  DeployerAgent({
    required this.taskService,
    required this.agentId,
  });

  Future<void> execute(Task task) async {
    try {
      await taskService.startTask(task.id);
      await taskService.addLog(task.id, 'DeployerAgent начал работу');

      final zipPath = task.metadata['zipPath'] as String?;
      final projectName = task.metadata['projectName'] as String? ?? 'agent-project';
      final repoName = (task.metadata['repoName'] as String?) ?? projectName.replaceAll(RegExp(r'[^a-zA-Z0-9_-]'), '-').toLowerCase();

      if (zipPath == null) {
        throw Exception('ZIP-путь не указан в metadata');
      }

      final github = ConnectorRegistry.instance.get('github');
      if (github == null || !github.isReady) {
        // Mock-режим
        await _mockDeploy(task, zipPath, repoName);
        return;
      }

      // 1. Создаём репозиторий
      await taskService.updateProgress(task.id, 0.15);
      await taskService.addLog(task.id, 'Создаю репозиторий $repoName...');
      final createRes = await github.execute('create_repo', {
        'name': repoName,
        'description': 'Generated by Agent City',
        'private': false,
      });
      if (!createRes.success) {
        throw Exception(createRes.error ?? 'Не удалось создать репо');
      }
      final repoUrl = createRes.data?['html_url'] as String? ?? 'https://github.com/.../$repoName';
      await taskService.addLog(task.id, 'Репозиторий: $repoUrl');

      // 2. Заливаем ZIP как Release
      await taskService.updateProgress(task.id, 0.35);
      await taskService.addLog(task.id, 'Загружаю ZIP в Release...');
      final uploadRes = await github.execute('upload_zip_as_release', {
        'repo': repoName,
        'zipPath': zipPath,
        'tag': 'v0.1.0-agent',
        'name': 'Agent City build',
      });
      if (!uploadRes.success) {
        await taskService.addLog(task.id, 'Предупреждение: ${uploadRes.error}');
      } else {
        await taskService.addLog(task.id, 'ZIP загружен: ${uploadRes.data?['download_url'] ?? "ok"}');
      }

      // 3. Триггерим workflow
      await taskService.updateProgress(task.id, 0.5);
      await taskService.addLog(task.id, 'Запускаю GitHub Actions (build_apk.yml)...');
      final triggerRes = await github.execute('trigger_workflow', {
        'repo': repoName,
        'workflow': 'build_apk.yml',
        'ref': 'main',
      });
      if (!triggerRes.success) {
        await taskService.addLog(task.id, 'Не удалось запустить workflow: ${triggerRes.error}');
        // Всё равно завершаем успешно — ZIP уже залит
        await taskService.completeTask(task.id, result: 'ZIP залит: $repoUrl\nWorkflow не запущен');
        return;
      }
      await taskService.addLog(task.id, 'Workflow запущен');

      // 4. Ждём завершения (polling)
      await taskService.updateProgress(task.id, 0.6);
      await taskService.addLog(task.id, 'Жду сборку APK (до 10 минут)...');

      String? apkUrl;
      String? conclusion;
      for (var i = 0; i < 30; i++) { // 30 * 20 сек = 10 мин
        await Future.delayed(const Duration(seconds: 20));
        final runsRes = await github.execute('get_workflow_runs', {
          'repo': repoName,
          'workflow': 'build_apk.yml',
          'perPage': 3,
        });
        if (runsRes.success && runsRes.data?['runs'] != null) {
          final runs = runsRes.data!['runs'] as List;
          if (runs.isNotEmpty) {
            final last = runs.first as Map;
            final status = last['status'] as String?;
            conclusion = last['conclusion'] as String?;
            await taskService.addLog(task.id, 'Статус: $status / $conclusion');
            await taskService.updateProgress(task.id, 0.6 + (i / 30) * 0.3);

            if (status == 'completed') {
              if (conclusion == 'success') {
                // Ссылка на run (артефакты внутри)
                apkUrl = last['html_url'] as String?;
                break;
              } else {
                throw Exception('Сборка упала: $conclusion');
              }
            }
          }
        }
      }

      if (apkUrl != null) {
        await taskService.addLog(task.id, 'APK готов! $apkUrl');
        await NotificationService.instance.showApkReady(repo: repoName, downloadUrl: apkUrl);
        await taskService.completeTask(
          task.id,
          result: 'Готово!\nРепо: $repoUrl\nAPK (Artifacts): $apkUrl',
        );
      } else {
        await taskService.addLog(task.id, 'Таймаут ожидания сборки. Проверь Actions вручную.');
        await taskService.completeTask(
          task.id,
          result: 'ZIP залит: $repoUrl\nСборка ещё идёт или таймаут. Смотри Actions.',
        );
      }
    } catch (e, st) {
      await taskService.failTask(task.id, e.toString());
      await taskService.addLog(task.id, 'Stack: $st');
    }
  }

  Future<void> _mockDeploy(Task task, String zipPath, String repoName) async {
    await taskService.addLog(task.id, '⚠️ GitHub не настроен — mock-режим');
    await Future.delayed(const Duration(seconds: 1));
    await taskService.updateProgress(task.id, 0.3);
    await taskService.addLog(task.id, 'Mock: репозиторий создан');
    await Future.delayed(const Duration(seconds: 1));
    await taskService.updateProgress(task.id, 0.6);
    await taskService.addLog(task.id, 'Mock: ZIP загружен');
    await Future.delayed(const Duration(seconds: 1));
    await taskService.updateProgress(task.id, 0.9);
    await taskService.addLog(task.id, 'Mock: GitHub Actions запущен и завершён');
    await NotificationService.instance.showApkReady(
      repo: repoName,
      downloadUrl: 'https://github.com/mock/$repoName/actions',
    );
    await taskService.completeTask(
      task.id,
      result: 'MOCK deploy OK.\nУкажи GITHUB_TOKEN + GITHUB_OWNER для реального деплоя.\nZIP: $zipPath',
    );
  }
}
